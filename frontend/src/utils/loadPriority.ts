/**
 * Очередь загрузки экрана по приоритетам.
 *
 * Открытый экран запрашивает сразу несколько вещей, и все они конкурируют за
 * одно соединение: на мобильной сети десяток параллельных запросов означает,
 * что и главный из них приедет последним. Порядок здесь задаётся смыслом, а не
 * порядком строк — сначала то, ради чего экран открыли, и только потом справки.
 *
 * Каждая ступень запускается целиком параллельно; следующая ждёт, пока
 * предыдущая закончится.
 */
export type LoadTask = () => unknown | Promise<unknown>

/**
 * Ступени в порядке убывания приоритета.
 *
 * Ошибка одной задачи не отменяет остальные и не обрывает очередь: провалившийся
 * второстепенный запрос не должен уносить с собой историю заказов, которая идёт
 * следом. Каждая задача сама отвечает за то, что показать при своей ошибке —
 * ресурсы экрана оставляют на месте прежнее значение.
 */
export async function loadByPriority(stages: LoadTask[][]): Promise<void> {
  for (const stage of stages) {
    if (!stage.length) continue
    await Promise.allSettled(stage.map((task) => task()))
  }
}
