// Карточка заказа берёт кнопки из `actions`, которые сервер собирает под того,
// кто смотрит. Список, сохранённый в кэш до этого, их не несёт: показанный
// первым кадром, он открыл бы карточку без кнопок — до первого ответа сети или
// насовсем, если сети нет. Такой кэш отбрасывается, и экран начинает с загрузки.
export const acceptPresentedOrders = (orders: unknown): boolean =>
  Array.isArray(orders) && orders.every((order) => order?.actions != null)
