-- 050_achievement_order_floor.sql
-- Порог суммы заказа, с которого ачивка засчитывается, опускается до нуля.
--
-- 047 поставила его равным 300 ₽, и это число не соответствовало каталогу:
-- стандартные услуги стоят 100–200 ₽, дороже порога оказалась одна передержка
-- за 800 ₽. То есть механизм был выключен не настройкой «выключено», а числом,
-- которое никто не видел: ядро отказывало со строкой
-- «order paid 100.00, below the 300.00 floor», и это была единственная улика.
--
-- Порог остаётся настройкой, а не исчезает: поднять его — одно значение в
-- system_settings, а поднять у одной ачивки — ключ min_order_amount в её
-- config. Ноль означает «границу проводит не сумма».
--
-- От накрутки при нулевом пороге по-прежнему защищают: заказчик и исполнитель
-- обязаны быть разными людьми, заказ обязан быть оплачен (положительная
-- итоговая сумма), суточный потолок баллов и требование N разных заказчиков у
-- ачивок с подарком.
UPDATE system_settings SET value = '0' WHERE key = 'achievement_min_order_amount';

-- Строки может не быть, если 047 применялась к базе, где ключ уже был занят
-- чем-то другим: ON CONFLICT DO NOTHING в ней означает «не трогать чужое».
INSERT INTO system_settings (key, value) VALUES ('achievement_min_order_amount', '0')
ON CONFLICT (key) DO NOTHING;
