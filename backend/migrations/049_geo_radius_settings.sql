-- 049_geo_radius_settings.sql
-- Оба гео-радиуса переезжают в настройки, редактируемые из админки.
--
-- Раньше их было не изменить, не пересобрав образ или не переписав клиент:
-- радиус взятия заказа читался из переменной окружения ACCEPT_RADIUS_KM с
-- зашитым умолчанием, радиус обзора карты был константой overviewRadiusKM =
-- 10.0 в коде, а список «Заказы поблизости» на дашборде и вовсе просил свои
-- 5 км числом в запросе. Три источника одной величины — ровно та почва, на
-- которой карта и список разошлись и заказ вне зоны стало возможно взять.
--
-- Значения ниже повторяют то, что действовало до этой миграции, поэтому сама
-- она поведение не меняет: она лишь делает величины видимыми и правимыми.
-- Радиус взятия остаётся тем же 0.5 км, что и был зашит в коде; администратор
-- меняет его в «Системные настройки», а не выкатом.

INSERT INTO system_settings (key, value) VALUES
    -- Насколько далеко исполнитель может взять заказ руками. Проверяется на
    -- сервере при взятии, и по нему же карта и список рисуют флаг can_accept.
    ('accept_radius_km', 0.5),
    -- Что показывать вокруг: радиус, в котором заказы попадают на карту и в
    -- список «Заказы поблизости». Всегда не меньше радиуса взятия, иначе
    -- исполнитель не увидит того, что ему разрешено брать.
    ('map_overview_radius_km', 10)
ON CONFLICT (key) DO NOTHING;
