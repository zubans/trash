// Package achievements переносит скрипты ачивок внутрь бинарника.
//
// Раскладка: по каталогу на ачивку, и имя каталога — это код, на который
// ссылается строка таблицы achievements.
//
//	achievements/
//	  fastest_gun/
//	    config.star        константы: окна, веса, пороги, тексты
//	    achievement.star   MANIFEST и хуки
//
// config.star выполняется первым, и его глобалы видны остальной части ачивки,
// поэтому правило и число, которое оно использует, правятся порознь.
//
// Скрипты — это данные, а не Go-код, в этом их смысл, но они должны ехать
// вместе с деплоем. Каталог (ACHIEVEMENTS_DIR) с той же раскладкой читается
// поверх этих при старте, чтобы правило можно было поправить без пересборки
// образа, — ровно как у поведений услуг.
